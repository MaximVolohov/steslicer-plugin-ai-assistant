def get_response(message):
    headers = {
        "Authorization": "Bearer {}".format(api_key),
        "Content-Type": "application/json"
    }

    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": message}
        ],
        "temperature": 0.3,
        "top_p": 0.9
    }

    try:
        response = requests.post(base_url, headers=headers, json=payload, timeout=90, verify=False)
        if response.status_code != 200:
            return "Ошибка сервера: {}".format(response.status_code)
            
        data = response.json()
        reply = data['choices'][0]['message']['content']
        
        try:
            command = json.loads(reply)
            if "tool" in command:
                tool_name = command["tool"]
                tool_args = command.get("args", {})
                
                result = mcp.tools_call(tool_name, tool_args)
                
                if result.get("status") == "success":
                    return "{}\n\n{}".format(
                        result.get("result", {}).get("message", "Выполнено"),
                        json.dumps(result.get("result", {}), ensure_ascii=False, indent=2)
                    )
                else:
                    return " Ошибка выполнения: {}".format(result.get("message"))
        except (json.JSONDecodeError, KeyError):
            pass
            
        return reply
        
    except Exception as e:
        return "Ошибка подключения: {}".format(str(e))